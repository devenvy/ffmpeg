#!/usr/bin/env bash
# libmp3lame (LAME) — MP3 audio encoder (LGPL-2.0). SOURCED by scripts/build.sh
# (shares its environment; appends its --enable-* to CONFIGURE_FLAGS where
# applicable). Not a standalone script.

[[ "${BUILD_LIBMP3LAME}" == "1" ]] || { echo "Skipping libmp3lame (not needed for ${RID})."; return 0; }

echo "Building libmp3lame (static)..."
cd "${WORK_DIR}" || exit 1
rm -rf lame-3.100
curl -fsSL --retry 3 --retry-delay 5 --retry-connrefused --connect-timeout 30 \
  "https://downloads.sourceforge.net/project/lame/lame/3.100/lame-3.100.tar.gz" -o lame.tar.gz
tar -xf lame.tar.gz
cd lame-3.100 || exit 1
# LAME 3.100 exports lame_init_old in its symbol file but no longer defines it,
# which breaks the link on strict toolchains. Drop it. Use -i.bak (an explicit backup
# suffix): BSD/macOS sed requires an argument after -i, whereas GNU's bare `sed -i`
# does not — the attached-suffix form works on both. (GNU-bare `sed -i` fails on the
# macOS/iOS runners with "command i expects \ followed by text".)
sed -i.bak '/lame_init_old/d' include/libmp3lame.sym
rm -f include/libmp3lame.sym.bak

LAME_ARGS=(--prefix="${DEPS_DIR}" --disable-shared --enable-static --disable-frontend --enable-nasm --with-pic)
LAME_ENV=()
case "${RID}" in
  win-x64)       LAME_ARGS+=(--host=x86_64-w64-mingw32) ;;
  linux-armhf)   LAME_ARGS+=(--host=arm-linux-gnueabihf) ;;
  android-arm64) LAME_ARGS+=(--host=aarch64-linux-android) ;;
  ios-arm64|ios-sim-arm64)
    LAME_ARGS+=(--host=aarch64-apple-darwin)
    # LAME 3.100 ships a configure generated by an OLD autoconf, whose AC_HEADER_STDC
    # uses a *runtime* probe. Cross-compiling to iOS can't run it, so STDC_HEADERS is
    # left undefined and mpglib/mpg123.h falls back to `#define memcpy(d,s,n) bcopy(...)`
    # — which Xcode's clang rejects as an undeclared function (C99). Supply the answer
    # configure can't probe (iOS has conforming STDC headers) so mpglib uses <string.h>.
    LAME_ENV+=(ac_cv_header_stdc=yes)
    ;;
esac
# Scope the cache override to configure only (via env) — don't leak it to later deps.
env "${LAME_ENV[@]+"${LAME_ENV[@]}"}" ./configure "${LAME_ARGS[@]}"
make -j"$(${NPROC})"
make install
CONFIGURE_FLAGS+=(--enable-libmp3lame)
echo "libmp3lame (MP3 encode) enabled."
